# logos -> white on transparent
def knock(src,name,invert_dark_bg=None):
    im=Image.open(os.path.join(A,src)).convert('RGBA'); W,H=im.size
    px=im.load(); bg=px[2,2]
    has_alpha = im.getextrema()[3][0] < 10
    bl=None if has_alpha else (bg[0]*.3+bg[1]*.59+bg[2]*.11)
    out=Image.new('RGBA',(W,H))
    op=out.load()
    for y in range(H):
        for x in range(W):
            r,g,b,a=px[x,y]
            l=r*.3+g*.59+b*.11
            if bl is None: al=a
            else: al=int(max(0,min(255,abs(l-bl)*2.4-40)))*a//255
            op[x,y]=(255,255,255,al)
    bb=out.getchannel('A').point(lambda v:255 if v>60 else 0).getbbox()
    if bb: out=out.crop(bb)
    out.thumbnail((480,160))
    out.save(os.path.join(OUT,f'{name}.webp'),'WEBP',quality=90,lossless=False)
    man[name]={'w':out.size[0],'h':out.size[1],'widths':[],'lqip':''}
