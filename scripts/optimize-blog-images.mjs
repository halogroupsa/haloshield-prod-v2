import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const assets = [
  { slug: "waterproofing-quotation-dubai", source: "exec-c7ece3a3-925a-4b05-a00e-746ae2e2f08b.png", alt: "Inspector reviewing building plans and a waterproofing sample at a timber table", references: ["moisture-meter-wall-inspection"], palette: "Warm timber, cream and olive" },
  { slug: "polyurea-waterproofing", source: "exec-9ce9827c-0892-4462-b578-e35979bb8084.png", alt: "Protected applicator spraying a seamless membrane across a commercial roof", references: ["halo-shield-team-burj-khalifa-rooftop", "palm-jumeirah-villa-rooftop-waterproofing"], palette: "Blue sky, slate and charcoal" },
  { slug: "mold-remediation", source: "exec-b0c83f5a-0f58-401c-a645-b188c1604126.png", alt: "Technician in protective equipment treating a damp wall in a terracotta-coloured room", references: ["moisture-meter-wall-inspection", "halo-shield-team-burj-khalifa-rooftop"], palette: "Terracotta, walnut and teal" },
  { slug: "mold-testing", source: "exec-85620f53-7c46-49d8-bd1a-689f576ee3bc.png", alt: "Gloved hands taking a surface swab beside an air sampling instrument", references: ["moisture-meter-wall-inspection"], palette: "Pale mint, white and blue" },
  { slug: "roof-leak-inspection-checklist-dubai", source: "exec-ad1684b2-17bb-449d-b554-8fcdcf4ec0ee.png", alt: "Inspector photographing a roof membrane defect near a drain after rain", references: ["moisture-meter-wall-inspection", "palm-jumeirah-villa-rooftop-waterproofing"], palette: "Silver, green and burgundy" },
];
const widths = [480, 960, 1536];
const output = path.join(root, "public/images/blogs");
await fs.mkdir(output, { recursive: true });
const images = {};
const provenance = [];
for (const asset of assets) {
  const source = path.join(root, "generated_images", asset.source);
  const meta = await sharp(source).metadata();
  const sizes = widths.filter((width) => width <= meta.width);
  const base = `/images/blogs/${asset.slug}`;
  for (const width of sizes) {
    await sharp(source).resize({ width }).webp({ quality: 78, effort: 6 }).toFile(path.join(output, `${asset.slug}-${width}.webp`));
  }
  const largest = sizes.at(-1);
  images[asset.slug] = { src: `${base}-${largest}.webp`, srcSet: sizes.map((w) => `${base}-${w}.webp ${w}w`).join(", "), width: meta.width, height: meta.height, alt: asset.alt };
  provenance.push({ slug: asset.slug, source: `generated_images/${asset.source}`, references: asset.references, palette: asset.palette, disclosure: "AI-generated illustration based on existing website photo references; not a record of a completed project." });
}
await fs.writeFile(path.join(root, "src/lib/blog-images.generated.ts"), `// Generated by scripts/optimize-blog-images.mjs; keep original images in generated_images.\nexport type BlogImageData = { src: string; srcSet: string; width: number; height: number; alt: string };\nexport const blogImages: Record<string, BlogImageData> = ${JSON.stringify(images, null, 2)};\n`);
await fs.writeFile(path.join(root, "docs/blog-image-provenance.json"), JSON.stringify(provenance, null, 2) + "\n");
console.log(`Optimised ${assets.length} blog illustrations into ${assets.length * widths.length} responsive WebP assets.`);
